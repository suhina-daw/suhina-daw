"""Suhina's feature map: docs/features.json, and what is written from it.

    python scripts/features.py            # write docs/features.md and the two figures
    python scripts/features.py --check    # what CI runs: the map is valid; writes nothing

docs/features.json lists every area Suhina aims at (ADR 0016) and the features in it, each done,
partly done or planned, in Suhina's own words. A pull request changes the status of what it
builds there. The list, the counts and the figures (docs/features-by-area.svg and its dark
version, shown at the top of the README) are written on main after every merge
(.github/workflows/docs-generated.yml), so pull requests change only the map and never conflict
on what is written from it.
"""

import argparse
import json
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "docs" / "features.json"
LIST = ROOT / "docs" / "features.md"
FIGURES = {"light": ROOT / "docs" / "features-by-area.svg", "dark": ROOT / "docs" / "features-by-area-dark.svg"}
STATUSES = ("done", "partial", "planned")
LABELS = {"done": "Done", "partial": "Partly done", "planned": "Planned"}
MARKS = {"done": "done", "partial": "partly done", "planned": "planned"}

# One hue, darkest for done, checked as an ordinal ramp against each surface.
THEMES = {
    "light": {"surface": "#fcfcfb", "ink": "#0b0b0b", "muted": "#52514e",
              "done": "#184f95", "partial": "#3987e5", "planned": "#86b6ef"},
    "dark": {"surface": "#1a1a19", "ink": "#f0efec", "muted": "#c3c2b7",
             "done": "#9ec5f4", "partial": "#3987e5", "planned": "#184f95"},
}


class MapError(Exception):
    pass


def load(path: Path = MAP) -> list:
    """The areas of the map, checked: names, statuses, no repeats."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise MapError(f"{path.name}: {error}")
    areas = data.get("areas") if isinstance(data, dict) else None
    if not isinstance(areas, list) or not areas:
        raise MapError("features.json: `areas` must be a list of at least one area")
    seen_areas = set()
    for area in areas:
        name = area.get("name") if isinstance(area, dict) else None
        if not isinstance(name, str) or not name.strip():
            raise MapError("features.json: every area needs a name")
        if name in seen_areas:
            raise MapError(f"features.json: area {name!r} appears twice")
        seen_areas.add(name)
        features = area.get("features")
        if not isinstance(features, list) or not features:
            raise MapError(f"features.json: area {name!r} has no features")
        seen = set()
        for feature in features:
            fname = feature.get("name") if isinstance(feature, dict) else None
            if not isinstance(fname, str) or not fname.strip():
                raise MapError(f"features.json: a feature of {name!r} has no name")
            if fname in seen:
                raise MapError(f"features.json: {fname!r} appears twice in {name!r}")
            seen.add(fname)
            if feature.get("status") not in STATUSES:
                raise MapError(f"features.json: {fname!r} has status {feature.get('status')!r}, "
                               f"not one of {', '.join(STATUSES)}")
            ref = feature.get("ref")
            if ref is not None and (not isinstance(ref, str) or not ref.strip()):
                raise MapError(f"features.json: {fname!r} has an empty ref")
    return areas


def counts(area: dict) -> dict:
    out = {s: 0 for s in STATUSES}
    for feature in area["features"]:
        out[feature["status"]] += 1
    return out


def ref_link(ref: str) -> str:
    if ref.startswith("#") and ref[1:].isdigit():
        return f"[{ref}](https://github.com/suhina-daw/suhina-daw/issues/{ref[1:]})"
    return ref


def markdown(areas: list) -> str:
    total = {s: sum(counts(a)[s] for a in areas) for s in STATUSES}
    all_features = sum(total.values())
    out = [
        "<!-- Generated by scripts/features.py from docs/features.json; edit that file instead. -->",
        "",
        "# What Suhina does today",
        "",
        f"{total['done']} of {all_features} features are done, {total['partial']} partly and "
        f"{total['planned']} planned, in the areas Suhina aims at "
        "([ADR 0016](decisions/0016-scope.md)). The order the planned ones are built in is in "
        "[ROADMAP.md](../ROADMAP.md).",
        "",
        "| Area | Done | Partly | Planned |",
        "|---|---|---|---|",
    ]
    for area in areas:
        c = counts(area)
        anchor = area["name"].lower().replace(" ", "-")
        anchor = "".join(ch for ch in anchor if ch.isalnum() or ch == "-")
        out.append(f"| [{area['name']}](#{anchor}) | {c['done']} | {c['partial']} | {c['planned']} |")
    for area in areas:
        out += ["", f"## {area['name']}", ""]
        for feature in area["features"]:
            line = f"- {feature['name']}: {MARKS[feature['status']]}"
            if feature.get("ref"):
                line += f" ({ref_link(feature['ref'])})"
            out.append(line)
    return "\n".join(out) + "\n"


def breakdown(c: dict) -> str:
    """"9 done · 1 partly · 4 planned", leaving out what is zero."""
    words = {"done": "done", "partial": "partly", "planned": "planned"}
    return " · ".join(f"{c[s]} {words[s]}" for s in STATUSES if c[s])


def svg(areas: list, theme: str) -> str:
    """One bar per area, the full width split into the shares done, partly done and planned,
    with the counts beside it; the first row is every area together."""
    t = THEMES[theme]
    label_w, bar_w, count_w, pad = 230, 330, 190, 16
    row, bar_h, top = 28, 16, 64
    total = {s: sum(counts(a)[s] for a in areas) for s in STATUSES}
    rows = [("All areas", total, True)] + [(a["name"], counts(a), False) for a in areas]
    width = pad + label_w + bar_w + count_w + pad
    height = top + row * len(rows) + 10 + pad
    font = "font-family=\"-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif\""
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-label="Suhina features by area: done, partly done and planned">',
        f'<rect width="{width}" height="{height}" rx="8" fill="{t["surface"]}"/>',
        f'<text x="{pad}" y="26" {font} font-size="15" font-weight="600" fill="{t["ink"]}">'
        'What Suhina does today, by area</text>',
    ]
    x = pad
    for status in STATUSES:
        out.append(f'<rect x="{x}" y="38" width="12" height="12" rx="3" fill="{t[status]}"/>')
        out.append(f'<text x="{x + 18}" y="48" {font} font-size="12" fill="{t["muted"]}">{LABELS[status]}</text>')
        # About 6.5 px a character at 12 px, then a gap.
        x += 18 + round(6.5 * len(LABELS[status])) + 18
    x0 = pad + label_w
    for i, (name, c, whole) in enumerate(rows):
        # The total stands apart from the areas below it.
        y = top + i * row + (0 if whole else 10)
        n = sum(c.values())
        weight = ' font-weight="600"' if whole else ""
        out.append(f'<text x="{x0 - 10}" y="{y + 12}" text-anchor="end" {font} '
                   f'font-size="12"{weight} fill="{t["ink"]}">{escape(name)}</text>')
        x = x0
        out.append(f'<clipPath id="bar{i}"><rect x="{x0}" y="{y}" width="{bar_w}" height="{bar_h}" rx="4"/></clipPath>')
        out.append(f'<g clip-path="url(#bar{i})">')
        for status in STATUSES:
            if c[status] == 0:
                continue
            w = bar_w * c[status] / n
            title = f"{name}: {c[status]} of {n} {MARKS[status]}"
            out.append(f'<rect x="{x:.1f}" y="{y}" width="{w:.1f}" height="{bar_h}" fill="{t[status]}">'
                       f'<title>{escape(title)}</title></rect>')
            x += w
            if x < x0 + bar_w - 0.5:
                # A 2 px gap of the surface between segments.
                out.append(f'<rect x="{x - 1:.1f}" y="{y}" width="2" height="{bar_h}" fill="{t["surface"]}"/>')
        out.append("</g>")
        out.append(f'<text x="{x0 + bar_w + 10}" y="{y + 12}" {font} font-size="12"{weight} '
                   f'fill="{t["muted"]}">{escape(breakdown(c))}</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check the map; write nothing")
    args = parser.parse_args()
    try:
        areas = load()
    except MapError as error:
        print(f"::error file=docs/features.json::{error}")
        return 1
    if args.check:
        n = sum(len(a["features"]) for a in areas)
        print(f"features.json: {len(areas)} areas, {n} features, fine")
        return 0
    LIST.write_text(markdown(areas), encoding="utf-8", newline="\n")
    for theme, path in FIGURES.items():
        path.write_text(svg(areas, theme), encoding="utf-8", newline="\n")
    print(f"wrote {LIST.relative_to(ROOT)} and the two figures")
    return 0


if __name__ == "__main__":
    sys.exit(main())
