# Regenerates crates/plugin-host/src/ara_sys.rs, the Rust form of the ARA C API, from the
# vendored headers in third_party/ara-api (ADR 0028). Needs bindgen-cli (`cargo install
# bindgen-cli`) and libclang. The output carries bindgen's layout checks, which fail to compile
# where a struct's size or a field's offset differs from the C headers'.
set -eu
root=$(git rev-parse --show-toplevel)
out="$root/crates/plugin-host/src/ara_sys.rs"
{
    echo "// @generated by scripts/ara_bindings.sh with bindgen $(bindgen --version | cut -d' ' -f2) from"
    echo "// third_party/ara-api/ARAInterface.h. DO NOT EDIT."
    echo "// The ARA API: Copyright (c) 2012-2025, Celemony Software GmbH, All Rights Reserved."
    echo "// Licensed under the Apache License, Version 2.0 (third_party/ara-api/LICENSE.txt)."
    echo "// SPDX-License-Identifier: Apache-2.0"
    echo
    bindgen "$root/third_party/ara-api/ARAInterface.h" \
        --allowlist-type 'ARA.*' --allowlist-var 'kARA.*' --no-doc-comments --use-core \
        --default-enum-style consts --no-prepend-enum-name \
        -- -x c -std=c11
} > "$out.tmp"
mv "$out.tmp" "$out"
rustfmt --edition 2024 "$out"
