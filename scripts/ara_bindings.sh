# Regenerates crates/plugin-host/src/ara_sys/{x86,arm}.rs, the Rust form of the ARA C API, from
# the vendored headers in third_party/ara-api (ADR 0028). The headers pack structs to 1 byte on
# x86 and to 8 on ARM, so each CPU gets a file of its own; crates/plugin-host/src/main.rs picks
# one by target_arch. Needs bindgen-cli (`cargo install bindgen-cli`) and libclang. The output
# carries bindgen's layout checks, which fail to compile where a struct's size or a field's offset
# differs from the C headers'.
set -eu
root=$(git rev-parse --show-toplevel)
generate() {
    out="$root/crates/plugin-host/src/ara_sys/$1.rs"
    {
        echo "// @generated by scripts/ara_bindings.sh with bindgen $(bindgen --version | cut -d' ' -f2) from"
        echo "// third_party/ara-api/ARAInterface.h for $2. DO NOT EDIT."
        echo "// The ARA API: Copyright (c) 2012-2025, Celemony Software GmbH, All Rights Reserved."
        echo "// Licensed under the Apache License, Version 2.0 (third_party/ara-api/LICENSE.txt)."
        echo "// SPDX-License-Identifier: Apache-2.0"
        echo
        bindgen "$root/third_party/ara-api/ARAInterface.h" \
            --allowlist-type 'ARA.*' --allowlist-var 'kARA.*' --no-doc-comments --use-core \
            --default-enum-style consts --no-prepend-enum-name \
            -- -x c -std=c11 -target "$2"
    } > "$out.tmp"
    mv "$out.tmp" "$out"
    rustfmt --edition 2024 --config-path "$root/rustfmt.toml" "$out"
}
mkdir -p "$root/crates/plugin-host/src/ara_sys"
generate x86 x86_64-apple-darwin
generate arm aarch64-apple-darwin
